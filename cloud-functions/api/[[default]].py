_GRAPH_TERM_LIMIT = 24
_GRAPH_COMMENT_DEFAULT = 520
_GRAPH_COMMENT_MAX = 1400
_GRAPH_SIM_THRESHOLD = 0.35
_GRAPH_CACHE = {}


def _term_node_index(idx, by_id):
    out = {}
    for key, rec in idx.items():
        node_id = f"term:{key}" if f"term:{key}" in by_id else ""
        info = {
            "term": rec.get("term") or key,
            "sentiment": rec.get("sentiment") or "",
            "node_id": node_id,
        }
        for name in [rec.get("term") or ""] + list(rec.get("aliases") or []):
            name = (name or "").strip().lower()
            if name:
                out.setdefault(name, info)
    return out


@app.route("/graph")
def api_graph():
    try:
        limit = int(request.args.get("comments", _GRAPH_COMMENT_DEFAULT))
    except ValueError:
        limit = _GRAPH_COMMENT_DEFAULT
    limit = max(0, min(limit, _GRAPH_COMMENT_MAX))

    if limit in _GRAPH_CACHE:
        return ok(_GRAPH_CACHE[limit])

    idx = _slang_index()
    nodes, by_id, edges = [], {}, []

    def add(node_id, label, kind, weight, extra=None):
        node = by_id.get(node_id)
        if node is None:
            node = {"id": node_id, "label": label, "kind": kind, "weight": 0, "degree": 0}
            if extra:
                node.update(extra)
            by_id[node_id] = node
            nodes.append(node)
        node["weight"] += max(0, weight or 0)
        return node

    term_recs = {}
    video_ctx = []
    for video in _videos():
        bvid = video["bvid"]
        corpus = _corpus(bvid)
        meta = corpus.get("meta", {})
        analyzed = _analyzed(bvid) or {}
        count = corpus.get("count") or len(corpus.get("comments", []))
        video_id = f"vid:{bvid}"
        add(video_id, video.get("name") or bvid, "video", count, {
            "bvid": bvid,
            "community": video["community"],
            "community_full": video.get("community_full", ""),
            "color": video.get("color", ""),
            "title": meta.get("title", ""),
            "owner": meta.get("owner", ""),
            "reply_count": meta.get("reply_count", 0),
            "anchor_count": sum(1 for a in _load_anchors() if a.get("bvid") == bvid),
            "analyzed": bool(analyzed),
        })

        for word in (analyzed.get("top_slang") or _corpus_top_slang(bvid))[:_GRAPH_TERM_LIMIT]:
            term = (word.get("term") or "").strip()
            if not term:
                continue
            key = term.lower()
            count = int(word.get("count") or 0)
            rec = idx.get(key, {})
            entry = term_recs.setdefault(key, {
                "label": rec.get("term") or term,
                "sentiment": rec.get("sentiment") or "未收录",
                "meaning": rec.get("meaning") or "",
                "note": rec.get("note") or "",
                "aliases": rec.get("aliases") or [],
                "examples": (rec.get("examples") or [])[:2],
                "count": 0,
                "videos": [],
            })
            entry["count"] += count
            if video.get("name") and video["name"] not in entry["videos"]:
                entry["videos"].append(video["name"])
            add(f"term:{key}", entry["label"], "term", count)
            edges.append({
                "source": video_id, "target": f"term:{key}",
                "relation": "出现", "weight": count, "pending": False,
            })
        video_ctx.append((video, video_id, corpus, analyzed))

    for key, entry in term_recs.items():
        by_id[f"term:{key}"].update({
            "sentiment": entry["sentiment"],
            "meaning": entry["meaning"],
            "note": entry["note"],
            "aliases": entry["aliases"],
            "examples": entry["examples"],
            "videos": entry["videos"],
            "count": entry["count"],
        })

    comment_stats = {
        "comments": 0, "sim_edges": 0, "mention_edges": 0,
        "near_dup_nodes": 0, "corpus_near_dup": 0, "corpus_unique": 0,
        "avg_sim": 0, "max_sim": 0, "comment_corpus": 0,
        "threshold": _GRAPH_SIM_THRESHOLD,
    }
    if limit:
        term_index = _term_node_index(idx, by_id)
        sim_sum, sim_n, max_sum = 0.0, 0, 0.0
        for video, video_id, corpus, analyzed in video_ctx:
            bvid = video["bvid"]
            layer = cg.build_comment_layer(
                corpus.get("comments", []), video_id=video_id, bvid=bvid,
                community=video["community"], color=video.get("color", ""),
                term_index=term_index, quota=limit,
                threshold=_GRAPH_SIM_THRESHOLD,
                analyzed_categories=_analyzed_comment_categories(bvid),
                rng_seed=20261022 + sum(ord(ch) for ch in bvid),
            )
            for node in layer["nodes"]:
                node.setdefault("degree", 0)
                by_id[node["id"]] = node
                nodes.append(node)
            edges.extend(layer["edges"])
            stats = layer["stats"]
            comment_stats["comments"] += stats["sampled"]
            comment_stats["sim_edges"] += stats["sim_edges"]
            comment_stats["mention_edges"] += stats.get("mention_edges", 0)
            comment_stats["near_dup_nodes"] += stats["linked"]
            comment_stats["corpus_near_dup"] += stats.get("corpus_linked", 0)
            comment_stats["corpus_unique"] += stats.get("unique", 0)
            comment_stats["comment_corpus"] += stats["raw"]
            sim_sum += stats["avg_sim"] * stats["sim_edges"]
            sim_n += stats["sim_edges"]
            max_sum = max(max_sum, stats["max_sim"])
        comment_stats["avg_sim"] = round(sim_sum / max(1, sim_n), 3)
        comment_stats["max_sim"] = round(max_sum, 3)

    for edge in edges:
        by_id[edge["source"]]["degree"] += 1
        by_id[edge["target"]]["degree"] += 1

    payload = {
        "nodes": nodes,
        "edges": edges,
        "stats": {
            "nodes": len(nodes), "edges": len(edges), "terms": len(term_recs),
            "videos": len(video_ctx),
            "corpus": sum(n["weight"] for n in nodes if n["kind"] == "video"),
            "analyzed": sum(1 for n in nodes if n["kind"] == "video" and n.get("analyzed")),
            **comment_stats,
        },
    }
    _GRAPH_CACHE[limit] = payload
    while len(_GRAPH_CACHE) > 4:
        _GRAPH_CACHE.pop(next(iter(_GRAPH_CACHE)))
    return ok(payload)


