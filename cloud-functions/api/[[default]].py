@app.route("/label/queue")
def api_label_queue():
    bvid = request.args.get("bvid")
    try:
        size = min(max(1, int(request.args.get("size", 100))), 200)
    except ValueError:
        size = 100
    anchors = _load_anchors()
    labeled = {a["rpid"] for a in anchors if a.get("bvid") == bvid}
    corpus = _corpus(bvid).get("comments", [])
    pool = [c for c in corpus if c.get("rpid") not in labeled and c.get("text")]

    limit_similar = 0.55
    random.shuffle(pool)
    seen_sets, seen_norms = [], set()
    for anchor in anchors:
        if anchor.get("bvid") != bvid:
            continue
        bg = _norm_bigrams(anchor.get("text", ""))
        if bg:
            seen_sets.append(bg)
            seen_norms.add("".join(sorted(bg)))

    diverse = []
    for comment in pool:
        bg = _norm_bigrams(comment["text"])
        if not bg:
            continue
        key = "".join(sorted(bg))
        if key in seen_norms:
            continue
        if any(_jaccard(bg, seen) >= limit_similar for seen in seen_sets):
            continue
        seen_sets.append(bg)
        seen_norms.add(key)
        diverse.append(comment)
        if len(diverse) >= max(size * 4, 400):
            break
    pool = diverse

    if not pool:
        return ok({"bvid": bvid, "labeled": len(labeled), "total_pool": 0, "items": []})

    short, mid, long_ = [], [], []
    for comment in pool:
        length = len(comment["text"])
        if length <= 12:
            short.append(comment)
        elif length <= 40:
            mid.append(comment)
        else:
            long_.append(comment)

    if size <= 100:
        n_short = int(size * 0.25)
        n_mid = int(size * 0.45)
        n_long = size - n_short - n_mid
    else:
        n_short = n_mid = size // 3
        n_long = size - 2 * n_short

    parts = []
    for group, count in ((short, n_short), (mid, n_mid), (long_, n_long)):
        random.shuffle(group)
        parts.extend(group[:count])
    random.shuffle(parts)

    return ok({
        "bvid": bvid,
        "labeled": len(labeled),
        "total_pool": len(pool),
        "items": [{
            "rpid": c["rpid"], "bvid": c["bvid"], "text": c["text"],
            "ctime": c.get("ctime"), "like": c.get("like", 0),
        } for c in parts],
    })


