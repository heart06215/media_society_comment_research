def _analyzed_comment_categories(bvid):
    """rpid -> category, taken from the persisted analysis rows."""
    analyzed = _analyzed(bvid) or {}
    out = {}
    for row in analyzed.get("_rows", []):
        if row.get("category") in CATEGORIES and row.get("rpid") is not None:
            out[str(row["rpid"])] = row["category"]
    return out


def _norm_bigrams(text):
    normalized = re.sub(r"[\s\W_]+", "", text or "")
    if len(normalized) < 2:
        return {normalized} if normalized else set()
    return {normalized[i:i + 2] for i in range(len(normalized) - 1)}


def _jaccard(a, b):
    if not a or not b:
        return 0.0
    inter = len(a & b)
    return inter / (len(a) + len(b) - inter) if inter else 0.0


