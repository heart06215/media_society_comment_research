def _chat_budget_ok():
    if CHAT_HOURLY_LIMIT <= 0:
        return True
    now = time.time()
    cutoff = now - 3600
    _CHAT_HITS[:] = [t for t in _CHAT_HITS if t >= cutoff]
    if len(_CHAT_HITS) >= CHAT_HOURLY_LIMIT:
        return False
    _CHAT_HITS.append(now)
    return True


# ---------- data helpers ----------
def _read_json(path: Path, default=None):
    try:
        with path.open("r", encoding="utf-8-sig") as fh:
            return json.load(fh)
    except (OSError, ValueError):
        return default


@lru_cache(maxsize=1)
def _public_config():
    for name in ("config.public.json", "config.example.json"):
        cfg = _read_json(DATA_DIR / name, {})
        if cfg:
            return cfg
    return {}


