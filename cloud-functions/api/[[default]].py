# ---------- response helpers ----------
def ok(data=None, **kw):
    body = {"success": True, "data": data or {}}
    body.update(kw)
    return jsonify(body)


def err(message, code=400):
    return jsonify({"success": False, "error": message}), code


def _basic_auth_ok():
    if not PUBLIC_BASIC_AUTH:
        return True
    auth = request.authorization
    if not auth or not auth.username or auth.password is None:
        return False
    try:
        want_user, want_pass = PUBLIC_BASIC_AUTH.split(":", 1)
    except ValueError:
        return False
    return (hmac.compare_digest(auth.username, want_user)
            and hmac.compare_digest(auth.password, want_pass))


@app.before_request
def _guard():
    if request.path == "/health":
        return None
    if not _basic_auth_ok():
        return Response("需要访问口令", 401,
                        {"WWW-Authenticate": 'Basic realm="powang", charset="UTF-8"'})
    # EdgeOne deployment is a read-only public snapshot. The chat endpoint is
    # the only allowed POST; it is still protected by the optional password and
    # by a process-local hourly budget.
    if request.method not in ("GET", "HEAD", "OPTIONS") and request.path != "/agent/chat":
        return err("EdgeOne 演示版为只读模式：不能修改数据或触发分析", 403)
    return None


