@lru_cache(maxsize=1)
def _load_lexicon_terms():
    terms = []
    for name in ("slang_dict.json", "rag_knowledge.json"):
        data = _read_json(DATA_DIR / name, {})
        for entry in data.get("entries", []):
            term = (entry.get("term") or "").strip()
            if term:
                terms.append(term)
            for alias in entry.get("aliases") or []:
                alias = (alias or "").strip()
                if alias:
                    terms.append(alias)
    seen, out = set(), []
    for term in terms:
        key = term.lower()
        if key not in seen:
            seen.add(key)
            out.append(term)
    return out


@lru_cache(maxsize=8)
def _corpus_top_slang(bvid, k=60):
    terms = _load_lexicon_terms()
    texts = [c.get("text") or "" for c in _corpus(bvid).get("comments", [])]
    scores, display = {}, {}
    for term in terms:
        key = term.lower()
        display.setdefault(key, term)
        count = sum(text.count(term) for text in texts)
        if count:
            scores[key] = scores.get(key, 0) + count
    counts = [{"term": display[key], "count": n} for key, n in scores.items() if n >= 1]
    counts.sort(key=lambda x: x["count"], reverse=True)
    return counts[:k]


@lru_cache(maxsize=1)
def _slang_index():
    idx = {}
    for name in ("slang_dict.json", "rag_knowledge.json"):
        for entry in _read_json(DATA_DIR / name, {}).get("entries", []):
            term = (entry.get("term") or "").strip()
            if not term:
                continue
            rec = idx.setdefault(term.lower(), {
                "term": term, "sentiment": "", "meaning": "", "note": "",
                "aliases": [], "examples": [],
            })
            rec["sentiment"] = rec["sentiment"] or (entry.get("sentiment") or "")
            rec["meaning"] = rec["meaning"] or (entry.get("meaning") or "")
            rec["note"] = rec["note"] or (entry.get("note") or "")
            for alias in entry.get("aliases") or []:
                if alias and alias not in rec["aliases"]:
                    rec["aliases"].append(alias)
            for example in entry.get("examples") or []:
                if example and example not in rec["examples"]:
                    rec["examples"].append(example)
    return idx


